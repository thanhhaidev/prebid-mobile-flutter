// Generates src/pages/changelog.md from every package's CHANGELOG.md, adding
// release dates (from the `<package>-v<version>` git tags) and links to
// pub.dev and GitHub diffs.
import {execFileSync} from 'node:child_process';
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const site = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(site, '..');
const repo = 'https://github.com/thanhhaidev/prebid-mobile-flutter';
const packages = ['prebid_mobile_sdk', 'prebid_mobile_sdk_gam', 'prebid_mobile_sdk_admob', 'prebid_mobile_sdk_max'];

/** The tag date as YYYY-MM-DD, or null when the tag is unknown (shallow clone). */
function tagDate(tag) {
  try {
    // The tagger date for annotated tags, the commit date for lightweight ones.
    return (
      execFileSync('git', ['for-each-ref', '--format=%(creatordate:short)', `refs/tags/${tag}`], {
        cwd: root,
        stdio: ['ignore', 'pipe', 'ignore'],
      })
        .toString()
        .trim() || null
    );
  } catch {
    return null;
  }
}

function longDate(iso) {
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    timeZone: 'UTC',
  });
}

/** Escapes MDX syntax (`<`, `{`, `}`) outside inline code and code blocks. */
function escapeMdx(markdown) {
  let inFence = false;
  return markdown
    .split('\n')
    .map((line) => {
      if (/^\s*```/.test(line)) {
        inFence = !inFence;
        return line;
      }
      if (inFence) return line;
      return line
        .split(/(`[^`]*`)/)
        .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;').replace(/[{}]/g, (c) => `\\${c}`)))
        .join('');
    })
    .join('\n');
}

/** "## [1.0.0] - 2026-10-10" / "## 1.0.0" sections; text before the first is dropped. */
function sections(source) {
  return source
    .split(/^## +/m)
    .slice(1)
    .map((chunk) => {
      const newline = chunk.indexOf('\n');
      const heading = chunk.slice(0, newline === -1 ? undefined : newline).trim();
      return {
        version: heading.match(/^\[?(\d[^\]\s]*)\]?/)?.[1] ?? null,
        name: heading,
        body: newline === -1 ? '' : chunk.slice(newline + 1).trim(),
      };
    });
}

const link = (label, href) => `<a href="${href}">${label}</a>`;

const out = [
  '---',
  'title: Changelog',
  'description: Release notes for every version of prebid_mobile_sdk and its companion packages.',
  'wrapperClassName: changelog-page',
  '---',
  '',
  '{/* Generated by scripts/sync-changelog.mjs from the packages\' CHANGELOG.md files. Do not edit. */}',
  '',
  '# Changelog',
  '',
  `Release notes for the core package and its companions, from each package's CHANGELOG.md. The native Prebid SDK version of every release is listed on the [Compatibility](/docs/compatibility) page.`,
  '',
];

let total = 0;
for (const name of packages) {
  const pub = `https://pub.dev/packages/${name}`;
  const entries = sections(readFileSync(join(root, 'packages', name, 'CHANGELOG.md'), 'utf8'));
  const versions = entries.filter((e) => e.version).map((e) => e.version);
  const latestReleased = versions.find((v) => tagDate(`${name}-v${v}`));

  entries.forEach(({version, name: heading, body}) => {
    const meta = [];
    const tag = (v) => `${name}-v${v}`;
    const previous = version ? versions[versions.indexOf(version) + 1] : versions[0];

    if (version) {
      const date = tagDate(tag(version));
      if (date) {
        meta.push(`Released ${longDate(date)}`);
        if (version === latestReleased) meta.push('<span className="release-latest">Latest</span>');
        meta.push(link('pub.dev', `${pub}/versions/${version}`));
        if (previous) meta.push(link('Diff', `${repo}/compare/${tag(previous)}...${tag(version)}`));
      } else {
        // Version bumped but not tagged yet.
        meta.push('Release pending');
        if (previous) meta.push(link(`Changes since v${previous}`, `${repo}/compare/${tag(previous)}...main`));
      }
    } else {
      meta.push('Not published yet');
      if (previous) meta.push(link(`Changes since v${previous}`, `${repo}/compare/${tag(previous)}...main`));
    }

    // "### **Added**:" -> "### Added"
    const cleaned = escapeMdx(body)
      .replace(/^(#{3,6}) +\*\*(.+?)\*\*:?\s*$/gm, '$1 $2')
      .replace(/^(#{3,6}) +(.+?):\s*$/gm, '$1 $2');

    out.push(`## ${name} ${version ? `v${version}` : heading}`, '', `<p className="release-meta">${meta.join(' · ')}</p>`, '', cleaned, '');
    total++;
  });
}

writeFileSync(join(site, 'src/pages/changelog.md'), `${out.join('\n').trim()}\n`);
console.log(`changelog: ${total} sections`);
